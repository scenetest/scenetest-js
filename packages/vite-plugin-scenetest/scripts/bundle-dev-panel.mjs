/**
 * Bundle the dev-panel TypeScript into a single IIFE string
 * This runs as part of the build process
 */

import * as esbuild from 'esbuild'
import { writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const srcDir = join(__dirname, '../src')

async function bundle() {
  const result = await esbuild.build({
    entryPoints: [join(srcDir, 'dev-panel/index.ts')],
    bundle: true,
    format: 'iife',
    minify: false, // Keep readable for debugging
    write: false,
    target: 'es2020',
  })

  const code = result.outputFiles[0].text

  // Generate the TypeScript file that exports the bundled script
  const output = `/**
 * Auto-generated dev panel script
 * DO NOT EDIT - this file is generated by scripts/bundle-dev-panel.mjs
 *
 * To modify the dev panel, edit files in src/dev-panel/ and run:
 *   pnpm run build:dev-panel
 */

export const devPanelScript = ${JSON.stringify(code)};
`

  writeFileSync(join(srcDir, 'dev-panel.generated.ts'), output)
  console.log('Generated src/dev-panel.generated.ts')
}

bundle().catch((err) => {
  console.error(err)
  process.exit(1)
})
